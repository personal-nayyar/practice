package LLD.util.user;

public class User {
    String id;
    String name;
    String email;
    String phone;
    String address;

    User(String id, String name, String email, String phone, String address) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.address = address;
    }
}

